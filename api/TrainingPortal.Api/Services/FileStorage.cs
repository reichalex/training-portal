namespace TrainingPortal.Api.Services;

/// <summary>
/// Where uploaded videos and article images are kept. The local implementation writes
/// to a folder (a disk or a network share); swap in Azure Blob Storage or S3 by
/// implementing this interface and registering it in Program.cs.
/// </summary>
public interface IFileStorage
{
    /// <summary>Saves the stream and returns the key to read it back with.</summary>
    Task<string> SaveAsync(Stream content, string extension, string folder, CancellationToken ct);
    /// <summary>A seekable stream (so video range requests work), or null if missing.</summary>
    Stream? OpenRead(string key);
    Task DeleteAsync(string key);
}

public class StorageOptions
{
    public string RootPath { get; set; } = "storage";
    public long MaxVideoBytes { get; set; } = 4L * 1024 * 1024 * 1024;
    public long MaxImageBytes { get; set; } = 10L * 1024 * 1024;
}

public class LocalFileStorage : IFileStorage
{
    private readonly string _root;

    public LocalFileStorage(Microsoft.Extensions.Options.IOptions<StorageOptions> options, IWebHostEnvironment env)
    {
        _root = Path.GetFullPath(Path.Combine(env.ContentRootPath, options.Value.RootPath));
        Directory.CreateDirectory(_root);
    }

    public async Task<string> SaveAsync(Stream content, string extension, string folder, CancellationToken ct)
    {
        var key = $"{folder}/{Guid.NewGuid():N}{extension.ToLowerInvariant()}";
        var path = PathFor(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = File.Create(path);
        await content.CopyToAsync(file, ct);
        return key;
    }

    public Stream? OpenRead(string key)
    {
        var path = PathFor(key);
        return File.Exists(path)
            ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 64 * 1024, useAsync: true)
            : null;
    }

    public Task DeleteAsync(string key)
    {
        var path = PathFor(key);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }

    private string PathFor(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_root, key));
        // Keys are generated by SaveAsync, but never let one escape the storage folder.
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new ArgumentException("Invalid storage key.", nameof(key));
        return path;
    }
}
